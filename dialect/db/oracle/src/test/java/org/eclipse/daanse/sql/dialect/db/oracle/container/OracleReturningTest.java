package org.eclipse.daanse.sql.dialect.db.oracle.container;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Types;
import java.util.ArrayList;
import java.util.List;

import org.eclipse.daanse.sql.dialect.api.DialectInitData;
import org.eclipse.daanse.sql.dialect.api.generator.ReturningGenerator;
import org.eclipse.daanse.sql.dialect.db.oracle.OracleDialect;
import org.junit.jupiter.api.condition.EnabledIfSystemProperty;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.testcontainers.containers.JdbcDatabaseContainer;

import oracle.jdbc.OraclePreparedStatement;

/**
 * Oracle brings back what an {@code INSERT}, an {@code UPDATE} and a {@code DELETE} wrote with
 * {@code RETURNING … INTO}, into out parameters, in every version: on 18, 21 and 23 the clause the dialect writes
 * brings back a key the database made, a default, a quoted column of mixed case, the new values of every row an update
 * wrote, the rows a delete removed and none where it removed none, after the statement's own parameter too. A
 * {@code RETURNING} clause alone, which a query would read back as rows, fails with ORA-00925 for every statement, 23
 * too, so the dialect writes none.
 */
@EnabledIfSystemProperty(named = "integration.docker", matches = "true")
class OracleReturningTest {

    /** A key the database makes, and a column of mixed case, which only a quoted name reaches, with a default. */
    private static final String SETUP = "CREATE TABLE ITEMS (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " NAME VARCHAR2(20), \"Note\" VARCHAR2(20) DEFAULT 'n/a')";

    @ParameterizedTest(name = "{0} -> RETURNING INTO")
    @ValueSource(strings = { "gvenzl/oracle-xe:18-slim-faststart", "gvenzl/oracle-xe:21-slim-faststart",
            "gvenzl/oracle-free:23.9-slim-faststart",
            "gvenzl/oracle-free:23.26.4-slim-faststart" })
    void returningInto(String image) throws Exception {
        try (JdbcDatabaseContainer<?> ora = OracleContainers.of(image)) {
            ora.start();
            try (Connection c = DriverManager.getConnection(ora.getJdbcUrl(), ora.getUsername(), ora.getPassword());
                    Statement st = c.createStatement()) {
                st.execute(SETUP);
                OracleDialect dialect = new OracleDialect(DialectInitData.fromConnection(c));
                ReturningGenerator ret = dialect.returningGenerator();

                assertThat(ret.supportsReturningInto()).as("supportsReturningInto").isTrue();
                assertThat(ret.returningInto(List.of("ID", "NAME"))).as("the clause")
                        .contains(" RETURNING \"ID\", \"NAME\" INTO ?, ?");
                assertThat(ret.returningInto(List.of("*"))).as("every column names no parameter").isEmpty();
                assertThat(ret.returningInto(List.of())).as("no columns, no clause").isEmpty();
                assertThat(ret.returningInto(null)).as("no columns, no clause").isEmpty();

                assertThat(returned(c, "INSERT INTO ITEMS(NAME) VALUES ('apple')" + into(ret, "ID"), types(N)))
                        .as("the key the database made").containsExactly("1");
                assertThat(returned(c, "INSERT INTO ITEMS(NAME) VALUES ('fig')" + into(ret, "Note"), types(S)))
                        .as("a quoted column of mixed case, its default").containsExactly("n/a");
                assertThat(returned(c, "INSERT INTO ITEMS(NAME) VALUES (?)" + into(ret, "ID", "NAME"), types(N, S),
                        "pear")).as("after the statement's own parameter").containsExactly("3|pear");
                returned(c, "INSERT INTO ITEMS(NAME) VALUES ('plum')" + into(ret, "ID"), types(N));

                assertThat(returned(c, "UPDATE ITEMS SET \"Note\" = 'sold' WHERE ID IN (1, 2)"
                        + into(ret, "ID", "Note"), types(N, S))).as("UPDATE, the new values of every row it wrote")
                        .containsExactlyInAnyOrder("1|sold", "2|sold");
                assertThat(returned(c, "DELETE FROM ITEMS WHERE NAME LIKE 'p%'" + into(ret, "NAME"), types(S)))
                        .as("DELETE, the rows it removed").containsExactlyInAnyOrder("pear", "plum");
                assertThat(returned(c, "DELETE FROM ITEMS WHERE ID = 99" + into(ret, "ID"), types(N)))
                        .as("nothing deleted, no row").isEmpty();

                // the form that returns rows: Oracle has none, in no version
                assertThat(ret.supportsReturning()).as("supportsReturning").isFalse();
                assertThat(ret.returning(List.of("ID"))).as("no RETURNING without INTO").isEmpty();
                for (String dml : List.of("INSERT INTO ITEMS(NAME) VALUES ('kiwi')",
                        "UPDATE ITEMS SET NAME = 'lime' WHERE ID = 1", "DELETE FROM ITEMS WHERE ID = 1")) {
                    assertThatThrownBy(() -> {
                        try (ResultSet rs = st.executeQuery(dml + " RETURNING \"ID\"")) {
                            rs.next();
                        }
                    }).as("RETURNING without INTO: " + dml).isInstanceOf(SQLException.class)
                            .hasMessageContaining("ORA-00925");
                }
            }
        }
    }

    private static final int N = Types.NUMERIC;
    private static final int S = Types.VARCHAR;

    private static int[] types(int... types) {
        return types;
    }

    private static String into(ReturningGenerator ret, String... columns) {
        return ret.returningInto(List.of(columns)).orElseThrow();
    }

    /**
     * Executes the statement with its own parameters, then binds an out parameter of each type after them, and reads
     * what the statement returned into them, a row per row written.
     */
    private static List<String> returned(Connection c, String sql, int[] types, String... params) throws SQLException {
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            OraclePreparedStatement ops = ps.unwrap(OraclePreparedStatement.class);
            for (int i = 0; i < params.length; i++) {
                ps.setString(i + 1, params[i]);
            }
            for (int i = 0; i < types.length; i++) {
                if (types[i] == S) {
                    ops.registerReturnParameter(params.length + i + 1, S, 20);
                } else {
                    ops.registerReturnParameter(params.length + i + 1, types[i]);
                }
            }
            ps.executeUpdate();
            List<String> out = new ArrayList<>();
            try (ResultSet rs = ops.getReturnResultSet()) {
                while (rs.next()) {
                    StringBuilder row = new StringBuilder();
                    for (int i = 1; i <= types.length; i++) {
                        if (i > 1)
                            row.append('|');
                        row.append(rs.getString(i));
                    }
                    out.add(row.toString());
                }
            }
            return out;
        }
    }
}
